export function EvidencePage() {
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedArtifactId, setSelectedArtifactId] = useState(mockArtifacts[0].id);

  const filtered = mockArtifacts.filter(a =>
    a.name.toLowerCase().includes(searchTerm.toLowerCase()) ||
    a.agent.toLowerCase().includes(searchTerm.toLowerCase())
  );

  const activeArtifact = mockArtifacts.find(a => a.id === selectedArtifactId) || mockArtifacts[0];

  return (
    <WorkspaceLayout
      title="Evidence"
      description="Inspect cryptographic artifacts, files, and outputs generated by Swarm specialist agents."
      state="ready"
      sprintStatus="Sprint 6.0"
    >
      <div className="flex h-full w-full bg-background-dark text-foreground overflow-hidden">
        
        {/* Left Side: Directory & File tree view */}
        <div className="w-80 border-r border-border-subtle flex flex-col min-h-0 bg-surface">
          {/* Search box */}
          <div className="p-4 border-b border-border-subtle flex items-center gap-2 bg-surface-elevated/25 shrink-0">
            <Search className="size-3.5 text-muted shrink-0" />
            <input
              type="text"
              placeholder="Search artifacts..."
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              className="bg-transparent text-xs w-full outline-none placeholder-muted/60"
            />
          </div>

          <div className="p-3 border-b border-border-subtle shrink-0">
            <span className="text-3xs font-mono text-muted uppercase tracking-wider">SWARM OUTPUT FILES</span>
          </div>

          <ScrollableArea className="flex-1 p-2">
            <div className="space-y-1">
              {filtered.map((item) => {
                const isSelected = item.id === selectedArtifactId;
                return (
                  <button
                    key={item.id}
                    onClick={() => setSelectedArtifactId(item.id)}
                    className={`w-full flex items-center justify-between p-2.5 rounded-lg border transition-all ${
                      isSelected
                        ? 'bg-accent/5 border-accent shadow-sm'
                        : 'bg-transparent border-transparent hover:bg-surface-elevated/40'
                    }`}
                  >
                    <div className="flex items-center gap-2 min-w-0">
                      {item.type === 'json' ? (
                        <FileCode className="size-4 text-accent shrink-0" />
                      ) : (
                        <FileText className="size-4 text-emerald-400 shrink-0" />
                      )}
                      <div className="text-left truncate">
                        <div className="text-xs font-mono font-medium text-foreground truncate">{item.name}</div>
                        <div className="text-3xs text-muted truncate">{item.agent}</div>
                      </div>
                    </div>
                    <ChevronRight className="size-3 text-muted shrink-0" />
                  </button>
                );
              })}
              {filtered.length === 0 && (
                <div className="text-center text-xs text-muted font-mono py-8">
                  No matching deliverables found
                </div>
              )}
            </div>
          </ScrollableArea>
        </div>

        {/* Middle Pane: Deliverable reader */}
        <div className="flex-1 flex flex-col min-h-0 bg-background overflow-hidden border-r border-border-subtle">
          <div className="px-6 py-4 border-b border-border-subtle bg-surface-elevated flex items-center justify-between shrink-0">
            <div className="flex items-center gap-2 font-mono">
              {activeArtifact.type === 'json' ? (
                <FileCode className="size-4 text-accent" />
              ) : (
                <FileText className="size-4 text-emerald-400" />
              )}
              <span className="text-sm font-semibold">{activeArtifact.name}</span>
            </div>
            <button
              onClick={() => {
                const element = document.createElement("a");
                const file = new Blob([activeArtifact.content], { type: 'text/plain' });
                element.href = URL.createObjectURL(file);
                element.download = activeArtifact.name;
                document.body.appendChild(element);
                element.click();
                document.body.removeChild(element);
              }}
              className="flex items-center gap-1.5 px-3 py-1.5 text-2xs border border-border-subtle hover:border-accent bg-surface-elevated hover:bg-surface transition-colors font-medium rounded-lg cursor-pointer"
            >
              <Download className="size-3.5" />
              Export Output
            </button>
          </div>

          <ScrollableArea className="flex-1 p-6">
            <div className="max-w-3xl mx-auto">
              {activeArtifact.type === 'markdown' ? (
                <div className="prose prose-invert max-w-none text-sm leading-relaxed space-y-4 font-sans text-foreground/90">
                  {/* Since this is a lightweight mockup, we render clean markdown representations */}
                  <div dangerouslySetInnerHTML={{ 
                    __html: activeArtifact.content
                      .replace(/^# (.*)$/gm, '<h1 class="text-xl font-bold border-b border-border-subtle pb-2 text-foreground">$1</h1>')
                      .replace(/^## (.*)$/gm, '<h2 class="text-lg font-semibold pt-4 text-foreground">$1</h2>')
                      .replace(/^### (.*)$/gm, '<h3 class="text-md font-semibold pt-2 text-foreground">$1</h3>')
                      .replace(/^- (.*)$/gm, '<li class="list-disc ml-5 text-muted">$1</li>')
                      .replace(/\*\*(.*)\*\*/g, '<strong class="text-accent font-bold">$1</strong>')
                  }} />
                </div>
              ) : (
                <pre className="text-2xs font-mono text-accent bg-surface-elevated/40 border border-border-subtle p-4 rounded-lg overflow-x-auto">
                  {activeArtifact.content}
                </pre>
              )}
            </div>
          </ScrollableArea>
        </div>

        {/* Right Side: Security verification & metadata */}
        <div className="w-80 flex flex-col min-h-0 bg-surface">
          <div className="p-4 border-b border-border-subtle bg-surface-elevated/40 shrink-0">
            <span className="text-2xs font-mono text-muted uppercase tracking-wider">Evidence Metadata</span>
          </div>

          <div className="p-4 space-y-6 flex-1 overflow-y-auto">
            {/* Cryptographic check */}
            <div className="p-3.5 border border-emerald-500/10 bg-emerald-500/5 rounded-lg flex items-start gap-3">
              <ShieldCheck className="size-5 text-emerald-400 shrink-0" />
              <div>
                <span className="text-xs font-mono font-bold text-emerald-400 block">SHA-256 SIGNED</span>
                <span className="text-3xs font-mono text-muted leading-tight mt-1 block break-all">
                  {activeArtifact.hash}
                </span>
              </div>
            </div>

            <div className="space-y-4 font-mono">
              <div className="p-3.5 border border-border-subtle bg-surface-elevated/30 rounded-lg flex items-center gap-3">
                <User className="size-4 text-muted shrink-0" />
                <div>
                  <span className="text-3xs text-muted uppercase block leading-none">Generated By</span>
                  <span className="text-xs font-semibold text-foreground mt-1.5 block">{activeArtifact.agent}</span>
                </div>
              </div>

              <div className="p-3.5 border border-border-subtle bg-surface-elevated/30 rounded-lg flex items-center gap-3">
                <HardDrive className="size-4 text-muted shrink-0" />
                <div>
                  <span className="text-3xs text-muted uppercase block leading-none">File Size</span>
                  <span className="text-xs font-semibold text-foreground mt-1.5 block">{activeArtifact.size}</span>
                </div>
              </div>

              <div className="p-3.5 border border-border-subtle bg-surface-elevated/30 rounded-lg flex items-center gap-3">
                <Calendar className="size-4 text-muted shrink-0" />
                <div>
                  <span className="text-3xs text-muted uppercase block leading-none">Verification Timestamp</span>
                  <span className="text-xs font-semibold text-foreground mt-1.5 block">{activeArtifact.verifiedAt}</span>
                </div>
              </div>
            </div>

            <div className="p-3 border border-border-subtle bg-surface-elevated/20 rounded-lg flex items-center gap-2">
              <CheckCircle2 className="size-4 text-emerald-400 shrink-0" />
              <span className="text-3xs font-mono text-muted uppercase">COMPLIANCE CRITERIA MET</span>
            </div>
          </div>
        </div>

      </div>
    </WorkspaceLayout>
  );
}
export default EvidencePage;
