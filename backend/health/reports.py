"""Generates operational reports and archives historical snapshots."""

import json
import shutil
from pathlib import Path
from datetime import datetime, timezone

from health.health_check import HealthMonitor
from health.resource_monitor import ResourceMonitor
from health.models import FailureReport, RecoveryReport, ResourceReport, SystemHealth


class HealthReporter:
    """Orchestrates health monitoring and report generation."""

    def __init__(self, artifacts_dir: str):
        self.artifacts_dir = Path(artifacts_dir)
        self.current_dir = self.artifacts_dir / "current"
        self.archive_dir = self.artifacts_dir / "archive" / "health"
        self.archive_dir.mkdir(parents=True, exist_ok=True)

        self.monitor = HealthMonitor(artifacts_dir)
        self.resource_monitor = ResourceMonitor(artifacts_dir)

    def _get_dir_size(self, directory: Path) -> int:
        """Helper to get size of a directory in bytes."""
        if not directory.exists():
            return 0
        return sum(f.stat().st_size for f in directory.rglob("*") if f.is_file())

    def generate_health_report(self) -> SystemHealth:
        system_health = self.monitor.aggregate_health()

        if not self.current_dir.exists():
            self.current_dir.mkdir(parents=True, exist_ok=True)

        with open(self.current_dir / "health_report.json", "w", encoding="utf-8") as f:
            f.write(system_health.model_dump_json(indent=2))

        return system_health

    def generate_failure_report(self, now_str: str) -> FailureReport:
        # Passively constructed from health monitor's aggregated state
        # Detailed failures could be expanded via EventBus if we stored them
        report = FailureReport(
            generated_at=now_str,
            total_failures=self.monitor.circuit_failures
            + self.monitor.terminal_failures,
            failures=[],
        )
        with open(self.current_dir / "failure_report.json", "w", encoding="utf-8") as f:
            f.write(report.model_dump_json(indent=2))
        return report

    def generate_recovery_report(self, now_str: str) -> RecoveryReport:
        report = RecoveryReport(
            generated_at=now_str,
            total_recoveries=0,
            successful_recoveries=0,
            failed_recoveries=0,
            events=[],
        )
        # Attempt to read the existing recovery report generated by RecoveryManager
        rm_report_path = self.artifacts_dir / "recovery_report.json"
        if rm_report_path.exists():
            try:
                with open(rm_report_path, "r", encoding="utf-8") as f:
                    rm_data = json.load(f)
                    report.total_recoveries = 1
                    if rm_data.get("status") == "RECOVERED":
                        report.successful_recoveries = 1
            except Exception:
                pass

        with open(
            self.current_dir / "recovery_report.json", "w", encoding="utf-8"
        ) as f:
            f.write(report.model_dump_json(indent=2))
        return report

    def generate_resource_report(self, now_str: str) -> ResourceReport:
        process = self.resource_monitor.get_process_metrics()
        fs = self.resource_monitor.get_filesystem_metrics()
        runtime = self.resource_monitor.get_runtime_metrics()
        cache = self.resource_monitor.get_cache_metrics()
        eb = self.resource_monitor.get_event_bus_metrics()
        cbs = self.resource_monitor.get_circuit_breaker_metrics()
        rp = self.resource_monitor.get_retry_metrics()

        violations = self.resource_monitor.evaluate_thresholds(process, fs)
        status = self.resource_monitor.aggregate_status(violations)

        report = ResourceReport(
            generated_at=now_str,
            overall_status=status,
            process=process,
            filesystem=fs,
            runtime=runtime,
            cache=cache,
            event_bus=eb,
            circuit_breakers=cbs,
            retry_policy=rp,
            violations=violations,
            recommendations=(
                ["Consider increasing resources if degraded."]
                if status != "HEALTHY"
                else []
            ),
        )
        with open(
            self.current_dir / "resource_report.json", "w", encoding="utf-8"
        ) as f:
            f.write(report.model_dump_json(indent=2))
        return report

    def generate_all_reports(self) -> None:
        """Generates all reports and saves them in artifacts/current."""
        now_str = datetime.now(timezone.utc).isoformat()

        self.generate_health_report()
        self.generate_failure_report(now_str)
        self.generate_recovery_report(now_str)
        self.generate_resource_report(now_str)
        self.generate_failure_injection_report(now_str)

    def generate_failure_injection_report(self, now_str: str) -> None:
        """Generates a failure injection report from current FailureInjector state."""
        from testing.failure_injection import FailureInjector  # noqa: PLC0415

        injector = FailureInjector.get_instance()
        stats = injector.statistics()

        report = {
            "generated_at": now_str,
            "active_profile": stats.active_profile,
            "injection_enabled": stats.enabled,
            "total_faults_configured": stats.total_faults_configured,
            "total_faults_triggered": stats.total_faults_triggered,
            "total_recoveries": stats.total_recoveries,
            "fault_details": stats.fault_details,
            "deterministic": True,
        }

        # Write to current
        report_path = self.current_dir / "failure_injection_report.json"
        with open(report_path, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2)

        # Archive under artifacts/archive/failure/ with timestamp — never overwrite
        failure_archive_dir = self.artifacts_dir / "archive" / "failure"
        failure_archive_dir.mkdir(parents=True, exist_ok=True)
        ts = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S_%f")
        archive_path = failure_archive_dir / f"failure_injection_{ts}.json"
        shutil.copy2(report_path, archive_path)

    def archive_snapshot(self) -> None:
        """Creates a timestamped archive of the current health reports."""
        now_str = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
        snapshot_dir = self.archive_dir / f"snapshot_{now_str}"
        snapshot_dir.mkdir(parents=True, exist_ok=True)

        for report_name in [
            "health_report.json",
            "failure_report.json",
            "recovery_report.json",
            "resource_report.json",
        ]:
            src = self.current_dir / report_name
            if src.exists():
                shutil.copy2(src, snapshot_dir / report_name)
